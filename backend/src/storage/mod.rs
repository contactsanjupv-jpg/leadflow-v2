//! Object storage abstraction (spec: provider-abstracted storage).
//!
//! Implemented provider: local filesystem (`LocalFsStorage`), suitable for a single node or a
//! shared/persistent volume. An S3-compatible provider is NOT implemented; add a new
//! `ObjectStorage` implementation and select it in `main.rs` when one is needed.

use std::path::PathBuf;

#[axum::async_trait]
pub trait ObjectStorage: Send + Sync {
    async fn put(&self, key: &str, bytes: &[u8]) -> anyhow::Result<()>;
    async fn get(&self, key: &str) -> anyhow::Result<Vec<u8>>;
}

pub struct LocalFsStorage {
    root: PathBuf,
}

impl LocalFsStorage {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        LocalFsStorage { root: root.into() }
    }

    /// Keys are generated by the server (`<org>/<doc>`), but are validated anyway so a bug can
    /// never turn into path traversal.
    fn path_for(&self, key: &str) -> anyhow::Result<PathBuf> {
        let valid = !key.is_empty()
            && !key.starts_with('/')
            && key.split('/').all(|seg| {
                !seg.is_empty()
                    && seg != "."
                    && seg != ".."
                    && seg
                        .chars()
                        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
            });
        if !valid {
            anyhow::bail!("invalid storage key");
        }
        Ok(self.root.join(key))
    }
}

#[axum::async_trait]
impl ObjectStorage for LocalFsStorage {
    async fn put(&self, key: &str, bytes: &[u8]) -> anyhow::Result<()> {
        let path = self.path_for(key)?;
        if let Some(parent) = path.parent() {
            tokio::fs::create_dir_all(parent).await?;
        }
        tokio::fs::write(&path, bytes).await?;
        Ok(())
    }

    async fn get(&self, key: &str) -> anyhow::Result<Vec<u8>> {
        Ok(tokio::fs::read(self.path_for(key)?).await?)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn round_trips_bytes_and_rejects_traversal() {
        let dir = std::env::temp_dir().join(format!("xflow-storage-test-{}", uuid::Uuid::new_v4()));
        let store = LocalFsStorage::new(&dir);
        store.put("org1/doc1", b"hello").await.unwrap();
        assert_eq!(store.get("org1/doc1").await.unwrap(), b"hello");
        for bad in ["../etc/passwd", "/abs", "a/../b", "a//b", "", "a/b c"] {
            assert!(
                store.put(bad, b"x").await.is_err(),
                "key {bad:?} must be rejected"
            );
        }
        let _ = std::fs::remove_dir_all(dir);
    }
}
